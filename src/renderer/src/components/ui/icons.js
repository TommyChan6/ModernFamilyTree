/** Strip variation selectors / skin tones so '⚔️' and '⚔' resolve alike. */
const bare = (s) =>
  Array.from(s)
    .filter((ch) => {
      const cp = ch.codePointAt(0)
      return cp !== 0xfe0e && cp !== 0xfe0f && !(cp >= 0x1f3fb && cp <= 0x1f3ff)
    })
    .join('')

/** The canonical icon name for any icon value (name, alias or legacy glyph). */
export function resolveIcon(value) {
  if (!value) return null
  const v = String(value)
  if (CUSTOM[v] || LUCIDE[v]) return v
  if (ALIASES[v]) return ALIASES[v]
  const b = bare(v).trim()
  return LEGACY_GLYPHS[b] || LEGACY_GLYPHS[v] || null
}

export function hasIcon(value) {
  return resolveIcon(value) != null
}

// Flat, self-closing SVG markup → [tag, attrs] pairs (Lucide's own format).
function compile(markup) {
  const out = []
  for (const m of markup.matchAll(/<(\w+)([^>]*?)\/>/g)) {
    const attrs = {}
    for (const a of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2]
    out.push([m[1], attrs])
  }
  return out
}
const CUSTOM_NODES = Object.fromEntries(Object.entries(CUSTOM).map(([k, v]) => [k, compile(v)]))

/** The [tag, attrs][] node list for an icon value, or null if unknown. */
export function iconNode(value) {
  const name = resolveIcon(value)
  if (!name) return null
  return CUSTOM_NODES[name] || LUCIDE[name] || null
}

